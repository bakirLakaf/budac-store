"""
باركود Code128 (النوع B) كـSVG — بلا أي مكتبة خارجية.

يستعمل فبوردرو الطباعة: كاميرا/قارئ شركة التوصيل يقرا رقم التتبّع.
يدعم الأحرف ASCII من 32 لـ126 (أرقام، حروف لاتينية، - ، _ ...).
"""

# أنماط Code128: كل رمز = 6 أرقام (عرض شريط/فراغ بالتناوب)، آخرهم STOP بـ7
_PATTERNS = [
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312",
    "132212", "221213", "221312", "231212", "112232", "122132", "122231", "113222",
    "123122", "123221", "223211", "221132", "221231", "213212", "223112", "312131",
    "311222", "321122", "321221", "312212", "322112", "322211", "212123", "212321",
    "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
    "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121",
    "313121", "211331", "231131", "213113", "213311", "213131", "311123", "311321",
    "331121", "312113", "312311", "332111", "314111", "221411", "431111", "111224",
    "111422", "121124", "121421", "141122", "141221", "112214", "112412", "122114",
    "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
    "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112",
    "421211", "212141", "214121", "412121", "111143", "111341", "131141", "114113",
    "114311", "411113", "411311", "113141", "114131", "311141", "411131", "211412",
    "211214", "211232", "2331112",
]
_START_B = 104
_STOP = 106


def clean_text(text):
    """يخلّي الأحرف المدعومة برك (ASCII 32..126)."""
    return "".join(ch for ch in str(text or "") if 32 <= ord(ch) <= 126)


def code128_svg(text, height=50, module=2):
    """يرجّع SVG نصّي، ولا '' إذا النص فارغ بعد التنظيف."""
    text = clean_text(text)
    if not text:
        return ""

    codes = [_START_B] + [ord(ch) - 32 for ch in text]
    checksum = _START_B
    for position, value in enumerate(codes[1:], start=1):
        checksum += position * value
    codes.append(checksum % 103)
    codes.append(_STOP)

    x = 10 * module   # هامش هادي (quiet zone)
    bars = []
    for code in codes:
        pattern = _PATTERNS[code]
        is_bar = True
        for width in pattern:
            w = int(width) * module
            if is_bar:
                bars.append(f'<rect x="{x}" y="0" width="{w}" height="{height}"/>')
            x += w
            is_bar = not is_bar
    total = x + 10 * module

    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total} {height}" '
        f'preserveAspectRatio="none" class="barcode-svg" role="img" '
        f'aria-label="{text}" fill="#000">{"".join(bars)}</svg>'
    )
