def run():
    app = create_app()
    with app.app_context():
        db.create_all()

        # 1) نتأكد أن شركات التوصيل موجودة
        carriers = {}
        for code, name in CARRIERS:
            carrier = Carrier.query.filter_by(code=code).first()
            if not carrier:
                carrier = Carrier(code=code, name=name, is_active=True)
                db.session.add(carrier)
                db.session.flush()
                print(f"🚚 شركة جديدة: {name}")
            carriers[code] = carrier

        # 2) نعمّرو/نحدّثو الأسعار
        created, updated = 0, 0

        for row in WILAYA_RATES:
            wilaya_code, wilaya_name = row[0], row[1]
            prices_by_carrier = {
                "zrexpress": (row[2], row[3]),
                "worldexpress": (row[4], row[5]),
                "yalidine": (row[6], row[7]),
            }

            for carrier_code, (home, office) in prices_by_carrier.items():
                carrier = carriers[carrier_code]
                rate = ShippingRate.query.filter_by(
                    carrier_id=carrier.id, wilaya_code=wilaya_code
                ).first()

                if rate:
                    rate.wilaya_name = wilaya_name
                    rate.home_price = home
                    rate.office_price = office
                    updated += 1
                else:
                    db.session.add(
                        ShippingRate(
                            carrier_id=carrier.id,
                            wilaya_code=wilaya_code,
                            wilaya_name=wilaya_name,
                            home_price=home,
                            office_price=office,
                        )
                    )
                    created += 1

        db.session.commit()

        total = len(WILAYA_RATES)
        print(f"\n✅ خلص! {total} ولاية × {len(CARRIERS)} شركات.")
        print(f"   أسعار جديدة: {created} | محدّثة: {updated}")

        # تقرير الولايات اللي فيها خدمة ناقصة — باش تكون عارف
        missing = (
            ShippingRate.query.filter(
                (ShippingRate.home_price.is_(None)) & (ShippingRate.office_price.is_(None))
            ).all()
        )
        if missing:
            print(f"\n⚠️  {len(missing)} حالة فيها الشركة ما تخدمش الولاية إطلاقًا:")
            for m in missing:
                print(f"   - {m.wilaya_display} @ {m.carrier.name}")


if __name__ == "__main__":
    run()
